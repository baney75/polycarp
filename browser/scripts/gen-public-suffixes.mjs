#!/usr/bin/env node
// Writes src/site-edits/public-suffixes.ts from the Public Suffix List (both sections: ICANN and private, like
// github.io and uk.com), so site edits can refuse a suffix many sites share. Rerun to refresh:
//   curl -sSo /tmp/psl.dat https://publicsuffix.org/list/public_suffix_list.dat && node scripts/gen-public-suffixes.mjs /tmp/psl.dat
// The list is MPL 2.0. Rules keep their order and are written in ASCII (punycode), the form a browser gives a host in.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) {
	console.error("usage: node scripts/gen-public-suffixes.mjs <public_suffix_list.dat>");
	process.exit(2);
}
const ascii = (name) => new URL(`http://${name}/`).hostname;
const rules = readFileSync(source, "utf8")
	.split("\n")
	.map((l) => l.trim().split(/\s/)[0])
	.filter((l) => l && !l.startsWith("//"))
	.map((l) => {
		const lower = l.toLowerCase();
		if (lower.startsWith("!")) return `!${ascii(lower.slice(1))}`;
		if (lower.startsWith("*.")) return `*.${ascii(lower.slice(2))}`;
		return ascii(lower);
	});
if (rules.length < 5000) throw new Error(`Only ${rules.length} rules: that isn't the whole list.`);
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "site-edits", "public-suffixes.ts");
writeFileSync(
	out,
	`// Generated by scripts/gen-public-suffixes.mjs from the Public Suffix List (https://publicsuffix.org, MPL 2.0).
// ${rules.length} rules, both sections, in ASCII. Don't edit by hand.
export const PUBLIC_SUFFIX_RULES = ${JSON.stringify(rules.join("\n"))};
`,
);
console.log(`${rules.length} rules -> ${out}`);
