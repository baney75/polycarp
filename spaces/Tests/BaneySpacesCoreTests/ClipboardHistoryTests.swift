import AppKit
import XCTest
@testable import BaneySpacesCore

/// Every test here copies to a private named pasteboard and keeps history in a temporary folder and a
/// throwaway defaults suite: nothing reads or changes the user's clipboard or settings.
final class ClipboardHistoryTests: XCTestCase {
    private var pb: NSPasteboard!
    private var dir: URL!
    private var defaults: UserDefaults!
    private var suite: String!
    private var clock = Date(timeIntervalSince1970: 1_800_000_000)

    override func setUp() {
        pb = NSPasteboard(name: NSPasteboard.Name("polycarp-test-\(UUID().uuidString)"))
        dir = FileManager.default.temporaryDirectory.appendingPathComponent("polycarp-clip-\(UUID().uuidString)")
        suite = "polycarp-test-\(UUID().uuidString)"
        defaults = UserDefaults(suiteName: suite)
    }

    override func tearDown() {
        pb.releaseGlobally()
        try? FileManager.default.removeItem(at: dir)
        defaults.removePersistentDomain(forName: suite)
    }

    private func makeStore(front: String? = "com.apple.TextEdit") -> ClipboardStore {
        ClipboardStore(file: dir.appendingPathComponent("clipboard.json"), pasteboard: pb, defaults: defaults,
                       frontApp: { front }, now: { [unowned self] in self.clock })
    }

    private func copy(_ text: String, marks: [String] = [], source: String? = nil) {
        pb.clearContents()
        var types: [NSPasteboard.PasteboardType] = [.string] + marks.map { NSPasteboard.PasteboardType($0) }
        if source != nil { types.append(NSPasteboard.PasteboardType(ClipboardPolicy.sourceType)) }
        pb.declareTypes(types, owner: nil)
        pb.setString(text, forType: .string)
        for m in marks { pb.setData(Data(), forType: NSPasteboard.PasteboardType(m)) }
        if let source { pb.setString(source, forType: NSPasteboard.PasteboardType(ClipboardPolicy.sourceType)) }
    }

    func testOffUntilTheMenuIsOpenedOnce() {
        let store = makeStore()
        copy("before")
        XCTAssertFalse(store.poll())
        XCTAssertEqual(store.entries, [])
        ClipboardProvider(store: store).opened()
        XCTAssertTrue(store.isEnabled)
        // What was on the pasteboard before history was on isn't kept.
        XCTAssertFalse(store.poll())
        copy("after")
        XCTAssertTrue(store.poll())
        XCTAssertEqual(store.entries.map(\.text), ["after"])
        store.stop()
    }

    /// The check in the brief: a concealed copy (a password manager's) must never appear in history.
    func testAConcealedCopyNeverAppearsInHistory() {
        let store = makeStore()
        store.enable()
        copy("hunter2", marks: ["org.nspasteboard.ConcealedType"])
        XCTAssertFalse(store.poll())
        copy("passing", marks: ["org.nspasteboard.TransientType"])
        XCTAssertFalse(store.poll())
        copy("generated", marks: ["org.nspasteboard.AutoGeneratedType"])
        XCTAssertFalse(store.poll())
        copy("old1p", marks: ["com.agilebits.onepassword"])
        XCTAssertFalse(store.poll())
        // A password manager's copy, marked or not, by its source marker or by being the app in front.
        copy("from-bitwarden", source: "com.bitwarden.desktop")
        XCTAssertFalse(store.poll())
        let fromFront = makeStore(front: "com.1password.1password")
        fromFront.enable()
        copy("from-1password")
        XCTAssertFalse(fromFront.poll())
        copy("plain")
        XCTAssertTrue(store.poll())
        XCTAssertEqual(store.entries.map(\.text), ["plain"])
        // Nor is any of it on disk.
        let disk = (try? String(contentsOf: store.file, encoding: .utf8)) ?? ""
        for secret in ["hunter2", "passing", "generated", "old1p", "from-bitwarden", "from-1password"] {
            XCTAssertFalse(disk.contains(secret), secret)
        }
        store.stop()
        fromFront.stop()
    }

    func testPolycarpsOwnSnippetPasteIsSkipped() {
        let store = makeStore()
        store.enable()
        LauncherPasteboard.copy("snippet text", transient: true, to: pb)
        XCTAssertFalse(store.poll())
        LauncherPasteboard.copy("calculator answer", to: pb)
        XCTAssertTrue(store.poll())
        store.stop()
    }

    func testEntriesExpireAfterTheRetentionAndTheDefaultIs24Hours() {
        let store = makeStore()
        store.enable()
        XCTAssertEqual(store.retentionHours, 24)
        copy("old")
        store.poll()
        clock += 23 * 3600
        copy("new")
        store.poll()
        XCTAssertEqual(store.entries.map(\.text), ["new", "old"])
        clock += 2 * 3600
        XCTAssertEqual(store.entries.map(\.text), ["new"])
        store.setRetention(hours: 1)
        XCTAssertEqual(ClipboardRetention.hours(defaults), 1)
        clock += 3601
        XCTAssertEqual(store.entries, [])
        store.stop()
    }

    func testStoredOnlyInItsOwnFileOwnerOnlyAndClearedByClearAll() throws {
        let store = makeStore()
        store.enable()
        copy("keep me")
        store.poll()
        let attrs = try FileManager.default.attributesOfItem(atPath: store.file.path)
        XCTAssertEqual((attrs[.posixPermissions] as? NSNumber)?.intValue, 0o600)
        XCTAssertEqual(try FileManager.default.contentsOfDirectory(atPath: dir.path), ["clipboard.json"])
        // A new store (the app relaunched) reads it back.
        XCTAssertEqual(makeStore().entries.map(\.text), ["keep me"])
        let provider = ClipboardProvider(store: store, now: { [unowned self] in self.clock })
        XCTAssertNil(provider.perform("clear"))
        XCTAssertEqual(store.entries, [])
        XCTAssertFalse(FileManager.default.fileExists(atPath: store.file.path))
        store.stop()
    }

    func testTurningItOffDeletesAndStops() {
        let store = makeStore()
        store.enable()
        copy("x")
        store.poll()
        XCTAssertEqual(ClipboardProvider(store: store).perform("off"), .close)
        XCTAssertFalse(store.isEnabled)
        XCTAssertEqual(store.entries, [])
        copy("y")
        XCTAssertFalse(store.poll())
    }

    func testHistoryDedupesAndStaysBounded() {
        var h = ClipboardHistory()
        let t = Date()
        h.add("a", at: t, app: nil)
        h.add("b", at: t, app: nil)
        h.add("a", at: t, app: nil)
        XCTAssertEqual(h.entries.map(\.text), ["a", "b"])
        XCTAssertFalse(h.add("   \n", at: t, app: nil))
        XCTAssertFalse(h.add(String(repeating: "x", count: ClipboardHistory.maxEntryBytes + 1), at: t, app: nil))
        for i in 0..<300 { h.add("item \(i)", at: t, app: nil) }
        XCTAssertEqual(h.entries.count, ClipboardHistory.maxEntries)
        var big = ClipboardHistory()
        for i in 0..<40 { big.add("\(i)" + String(repeating: "y", count: 100_000), at: t, app: nil) }
        XCTAssertLessThanOrEqual(big.entries.reduce(0) { $0 + $1.text.utf8.count }, ClipboardHistory.maxTotalBytes)
        XCTAssertTrue(big.entries.first!.text.hasPrefix("39"))
    }

    func testTheMenuListsNewestFirstAndOffersTheCommands() {
        let store = makeStore()
        let provider = ClipboardProvider(store: store, now: { [unowned self] in self.clock })
        provider.opened()
        XCTAssertEqual(provider.listing("").first?.title, "Nothing copied yet")
        copy("first line\nsecond")
        store.poll()
        copy("other")
        store.poll()
        let rows = provider.listing("")
        XCTAssertEqual(rows.prefix(2).map(\.title), ["other", "first line ⏎ second"])
        XCTAssertEqual(rows[1].action, .copy("first line\nsecond"))
        XCTAssertEqual(rows.suffix(3).map(\.id), ["clip-keep", "clip-clear", "clip-off"])
        XCTAssertNotNil(rows.first { $0.id == "clip-clear" }?.confirm)
        XCTAssertEqual(provider.listing("second").first?.title, "first line ⏎ second")
        // Never in the main search.
        XCTAssertEqual(provider.results(for: "other"), [])
        XCTAssertNil(provider.perform("keep"))
        XCTAssertEqual(store.retentionHours, 168)
        store.stop()
    }

    func testPasswordManagersAreKnownByBundleID() {
        for id in ["com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop", "me.proton.pass.electron",
                   "org.keepassxc.keepassxc", "com.apple.keychainaccess", "com.apple.Passwords", "com.lastpass.LastPass"] {
            XCTAssertTrue(ClipboardPolicy.isPasswordManager(id), id)
        }
        XCTAssertFalse(ClipboardPolicy.isPasswordManager("com.apple.Safari"))
        XCTAssertFalse(ClipboardPolicy.isPasswordManager(nil))
    }
}

final class ClipboardWiringTests: XCTestCase {
    /// The app keeps one store from launch (so history fills while the launcher is closed), gives it to the
    /// launcher, and the launcher has a Clipboard menu whose rows can ask first and run provider commands.
    func testTheAppWatchesFromLaunchAndTheLauncherHasTheMenu() throws {
        let app = try String(contentsOfFile: LauncherProviderSeamTests.source("Sources/BaneySpaces/AppDelegate.swift"), encoding: .utf8)
        for needle in ["ClipboardStore(file: Spaces.folder.appendingPathComponent(\"clipboard.json\"))", "clipboard.start()",
                       "ClipboardProvider(store: clipboard)"] {
            XCTAssertTrue(app.contains(needle), needle)
        }
        let launcher = try String(contentsOfFile: LauncherProviderSeamTests.source("Sources/BaneySpaces/Launcher.swift"), encoding: .utf8)
        for needle in ["case root, web, apps, files, install, remove, update, system, workspaces, clipboard",
                       "case .command(let provider, let id)", "if let question = r.confirm", ".opened()"] {
            XCTAssertTrue(launcher.contains(needle), needle)
        }
    }
}
