import AppKit

/// Text copied on this Mac, newest first, for the launcher's Clipboard menu. Off until the person opens
/// that menu once. Kept only in a file in Polycarp's support folder (owner-only, out of backups), for
/// 24 hours unless they choose otherwise, and never anything a password manager or app marks private.
public struct ClipboardEntry: Codable, Equatable, Sendable {
    public let text: String
    public let copiedAt: Date
    /// The bundle id of the app it was copied from, when known.
    public let app: String?

    public init(text: String, copiedAt: Date, app: String?) {
        self.text = text
        self.copiedAt = copiedAt
        self.app = app
    }
}

public struct ClipboardHistory: Equatable, Sendable {
    public private(set) var entries: [ClipboardEntry]
    public static let maxEntries = 200
    /// Text longer than this isn't kept: a whole file pasted around belongs in a file.
    public static let maxEntryBytes = 200 * 1024
    /// All entries together stay under this, oldest dropped first, so the history stays small in memory.
    public static let maxTotalBytes = 2 * 1024 * 1024

    public init(_ entries: [ClipboardEntry] = []) { self.entries = entries }

    /// Newest first; the same text copied again moves to the top instead of showing twice.
    @discardableResult
    public mutating func add(_ text: String, at date: Date, app: String?) -> Bool {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.utf8.count <= Self.maxEntryBytes else { return false }
        entries.removeAll { $0.text == text }
        entries.insert(ClipboardEntry(text: text, copiedAt: date, app: app), at: 0)
        var total = 0
        var keep = 0
        for e in entries {
            total += e.text.utf8.count
            if keep == Self.maxEntries || total > Self.maxTotalBytes { break }
            keep += 1
        }
        entries.removeLast(entries.count - keep)
        return true
    }

    /// Drops what was copied more than `retention` seconds before `now`. True when anything went.
    @discardableResult
    public mutating func prune(now: Date, retention: TimeInterval) -> Bool {
        let cutoff = now.addingTimeInterval(-retention)
        let before = entries.count
        entries.removeAll { $0.copiedAt < cutoff }
        return entries.count != before
    }

    public mutating func clear() { entries.removeAll() }

    /// Entries whose text holds what was typed (case and accents ignored), newest first.
    public func search(_ query: String) -> [ClipboardEntry] {
        let q = Fuzzy.fold(query)
        guard !q.isEmpty else { return entries }
        return entries.filter { Fuzzy.fold($0.text).contains(q) }
    }
}

/// What clipboard history never keeps.
public enum ClipboardPolicy {
    /// nspasteboard.org markers: concealed (a password), transient (passing through), auto-generated,
    /// plus the older ones 1Password and others still write.
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
        "com.typeit4me.clipping", "net.antelle.keeweb",
    ]
    /// The marker that names the app a copy came from.
    public static let sourceType = "org.nspasteboard.source"

    /// Password managers, by a piece of their bundle id: whatever they copy is skipped, marked or not.
    static let vaultApps = ("1password onepassword bitwarden keepass lastpass dashlane enpass proton.pass protonpass "
                            + "keychainaccess com.apple.passwords keeweb nordpass roboform strongbox secrets").split(separator: " ")

    public static func isPasswordManager(_ bundleID: String?) -> Bool {
        guard let id = bundleID?.lowercased() else { return false }
        return vaultApps.contains { id.contains($0) }
    }

    /// Whether a copy with these pasteboard types, from this app, may go into history.
    public static func mayKeep(types: [String], source: String?) -> Bool {
        if types.contains(where: privateTypes.contains) { return false }
        return !isPasswordManager(source)
    }
}

/// How long history keeps an entry: `defaults write com.baney.polycarp clipboardHistoryHours -int N`
/// (1 to 720), or the Keep row in the Clipboard menu. 24 hours unless set.
public enum ClipboardRetention {
    public static let key = "clipboardHistoryHours"
    public static let defaultHours = 24
    /// The choices the Keep row steps through.
    public static let choices = [1, 24, 168]

    public static func hours(_ defaults: UserDefaults = .standard) -> Int {
        let h = defaults.integer(forKey: key)
        return h == 0 ? defaultHours : min(max(h, 1), 720)
    }

    public static func next(after h: Int) -> Int {
        choices.first { $0 > h } ?? choices[0]
    }

    public static func label(_ h: Int) -> String {
        h % 24 == 0 && h >= 48 ? "\(h / 24) days" : h == 1 ? "1 hour" : "\(h) hours"
    }
}

/// Clipboard history in memory and on disk, and the watch on a pasteboard that fills it.
public final class ClipboardStore {
    /// `defaults write com.baney.polycarp clipboardHistory -bool true|false`. Unset (off) until the
    /// Clipboard menu is opened once.
    public static let enabledKey = "clipboardHistory"

    public let file: URL
    private let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private let frontApp: () -> String?
    private let now: () -> Date
    private var lastChange: Int
    private var loaded = false
    private var history = ClipboardHistory()
    private var timer: Timer?
    private var polls = 0

    public init(file: URL, pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard,
                frontApp: @escaping () -> String? = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier },
                now: @escaping () -> Date = Date.init) {
        self.file = file
        self.pasteboard = pasteboard
        self.defaults = defaults
        self.frontApp = frontApp
        self.now = now
        // What's on the pasteboard when the watch starts was copied before it, so it isn't kept.
        lastChange = pasteboard.changeCount
    }

    public var isEnabled: Bool { defaults.bool(forKey: Self.enabledKey) }
    public var retentionHours: Int { ClipboardRetention.hours(defaults) }

    /// Turns history on (the menu was opened) and starts the watch. History starts now.
    public func enable() {
        guard !isEnabled else { return start() }
        defaults.set(true, forKey: Self.enabledKey)
        lastChange = pasteboard.changeCount
        start()
    }

    /// Turns history off, stops the watch and deletes what was kept.
    public func disable() {
        defaults.set(false, forKey: Self.enabledKey)
        stop()
        clear()
    }

    /// Starts polling the pasteboard if history is on. A poll is one `changeCount` read.
    public func start() {
        guard isEnabled, timer == nil else { return }
        load()
        lastChange = pasteboard.changeCount
        let t = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.25
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    public var entries: [ClipboardEntry] {
        load()
        if history.prune(now: now(), retention: retention) { save() }
        return history.entries
    }

    public func search(_ q: String) -> [ClipboardEntry] {
        _ = entries
        return history.search(q)
    }

    public func clear() {
        history.clear()
        loaded = true
        try? FileManager.default.removeItem(at: file)
    }

    public func setRetention(hours: Int) {
        defaults.set(hours, forKey: ClipboardRetention.key)
        if history.prune(now: now(), retention: retention) { save() }
    }

    private var retention: TimeInterval { TimeInterval(retentionHours) * 3600 }

    /// Looks at the pasteboard once: a new copy that may be kept goes to the top. True when one was kept.
    @discardableResult
    public func poll() -> Bool {
        guard isEnabled else { return false }
        polls += 1
        // About once a minute, entries past their time go even if nothing is copied.
        if polls % 80 == 0, history.prune(now: now(), retention: retention) { save() }
        let change = pasteboard.changeCount
        guard change != lastChange else { return false }
        lastChange = change
        let types = (pasteboard.types ?? []).map(\.rawValue)
        let source = pasteboard.string(forType: NSPasteboard.PasteboardType(ClipboardPolicy.sourceType)) ?? frontApp()
        guard ClipboardPolicy.mayKeep(types: types, source: source),
              let text = pasteboard.string(forType: .string) else { return false }
        load()
        guard history.add(text, at: now(), app: source) else { return false }
        save()
        return true
    }

    private func load() {
        guard !loaded else { return }
        loaded = true
        guard let data = try? Data(contentsOf: file),
              let list = try? JSONDecoder.clipboard.decode([ClipboardEntry].self, from: data) else { return }
        history = ClipboardHistory(list)
        if history.prune(now: now(), retention: retention) { save() }
    }

    /// Owner-only, written whole, and out of Time Machine.
    private func save() {
        let fm = FileManager.default
        try? fm.createDirectory(at: file.deletingLastPathComponent(), withIntermediateDirectories: true)
        guard let data = try? JSONEncoder.clipboard.encode(history.entries) else { return }
        let tmp = file.appendingPathExtension("tmp")
        guard fm.createFile(atPath: tmp.path, contents: data, attributes: [.posixPermissions: 0o600]) else { return }
        guard rename(tmp.path, file.path) == 0 else { try? fm.removeItem(at: tmp); return }
        var url = file
        var values = URLResourceValues()
        values.isExcludedFromBackup = true
        try? url.setResourceValues(values)
    }
}

private extension JSONEncoder {
    static var clipboard: JSONEncoder {
        let e = JSONEncoder()
        e.dateEncodingStrategy = .secondsSince1970
        return e
    }
}

private extension JSONDecoder {
    static var clipboard: JSONDecoder {
        let d = JSONDecoder()
        d.dateDecodingStrategy = .secondsSince1970
        return d
    }
}
