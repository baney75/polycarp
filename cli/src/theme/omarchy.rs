/// `#rrggbb` from `#rrggbb`, `#rgb`, `0xrrggbb` or bare `rrggbb`, in any case.
fn norm_hex(s: &str) -> Option<String> {
    let t = s.trim();
    let t = t
        .strip_prefix('#')
        .or_else(|| t.strip_prefix("0x"))
        .or_else(|| t.strip_prefix("0X"))
        .unwrap_or(t);
    if !t.chars().all(|c| c.is_ascii_hexdigit()) {
        return None;
    }
    let full = match t.len() {
        6 => t.to_string(),
        3 => t.chars().flat_map(|c| [c, c]).collect(),
        _ => return None,
    };
    Some(format!("#{}", full.to_lowercase()))
}

fn to_hsl(hex: &str) -> (f64, f64, f64) {
    let b = |i: usize| {
        f64::from(
            hex.get(i..i + 2)
                .and_then(|h| u8::from_str_radix(h, 16).ok())
                .unwrap_or(0),
        ) / 255.0
    };
    let (r, g, bl) = (b(1), b(3), b(5));
    let max = r.max(g).max(bl);
    let min = r.min(g).min(bl);
    let l = (max + min) / 2.0;
    let d = max - min;
    if d == 0.0 {
        return (0.0, 0.0, l);
    }
    let s = d / (1.0 - (2.0 * l - 1.0).abs());
    let h = if max == r {
        ((g - bl) / d).rem_euclid(6.0)
    } else if max == g {
        (bl - r) / d + 2.0
    } else {
        (r - g) / d + 4.0
    };
    (h * 60.0, s, l)
}

fn from_hsl(h: f64, s: f64, l: f64) -> String {
    let c = (1.0 - (2.0 * l - 1.0).abs()) * s;
    let x = c * (1.0 - ((h / 60.0).rem_euclid(2.0) - 1.0).abs());
    let m = l - c / 2.0;
    let (r, g, b) = match (h / 60.0).floor() as i64 {
        0 => (c, x, 0.0),
        1 => (x, c, 0.0),
        2 => (0.0, c, x),
        3 => (0.0, x, c),
        4 => (x, 0.0, c),
        _ => (c, 0.0, x),
    };
    let q = |v: f64| ((v + m) * 255.0).round().clamp(0.0, 255.0) as u8;
    format!("#{:02x}{:02x}{:02x}", q(r), q(g), q(b))
}

/// One color that was moved to make it readable.
#[derive(Clone)]
struct Nudge {
    path: String,
    from: String,
    to: String,
    reason: String,
}

impl Nudge {
    fn note(&self) -> String {
        format!(
            "{}: {} {}; now {}",
            self.path, self.from, self.reason, self.to
        )
    }
    fn json(&self) -> Json {
        json!({"path": self.path, "from": self.from, "to": self.to, "reason": self.reason})
    }
}

/// The pairs `role` is the text of, with the color it sits on now.
fn constraints(colors: &Colors, role: &str) -> Vec<(String, String, f64)> {
    pairs()
        .into_iter()
        .filter(|(fg, _, _)| *fg == role)
        .filter_map(|(_, bg, min)| {
            colors
                .get(bg)
                .filter(|c| is_hex(c))
                .map(|c| (bg.to_string(), c.clone(), min))
        })
        .collect()
}

fn passes(color: &str, cons: &[(String, String, f64)]) -> bool {
    cons.iter().all(|(_, bg, min)| contrast(color, bg) >= *min)
}

/// The color nearest `color` in lightness (same hue and saturation) that passes every constraint.
/// On a tie the direction of the mode wins: lighter on dark, darker on light.
fn nearest_passing(
    color: &str,
    cons: &[(String, String, f64)],
    lighter_first: bool,
) -> Option<String> {
    if passes(color, cons) {
        return Some(color.to_string());
    }
    let (h, s, l) = to_hsl(color);
    let dirs = if lighter_first {
        [1.0, -1.0]
    } else {
        [-1.0, 1.0]
    };
    for k in 1..=((1.0 / STEP) as usize) {
        for dir in dirs {
            let nl = l + dir * STEP * k as f64;
            if !(0.0..=1.0).contains(&nl) {
                continue;
            }
            let cand = from_hsl(h, s, nl);
            if passes(&cand, cons) {
                return Some(cand);
            }
        }
    }
    None
}

/// Moves `role` in `colors` if it fails, and records the move.
fn settle_role(mode: &str, colors: &mut Colors, role: &str, nudges: &mut Vec<Nudge>) {
    let Some(from) = colors.get(role).cloned().filter(|c| is_hex(c)) else {
        return;
    };
    let cons = constraints(colors, role);
    if cons.is_empty() {
        return;
    }
    if passes(&from, &cons) {
        return;
    }
    let lighter = mode == "dark";
    let to = nearest_passing(&from, &cons, lighter).or_else(|| {
        // No lightness of this hue reads on every background. Black or white is the last resort.
        ["#000000", "#ffffff"]
            .into_iter()
            .filter(|c| passes(c, &cons))
            .map(str::to_string)
            .next()
    });
    let Some(to) = to else { return };
    let worst = cons
        .iter()
        .map(|(bg, c, min)| (contrast(&from, c), bg, *min))
        .min_by(|a, b| a.0.total_cmp(&b.0))
        .expect("a failing role has a pair");
    nudges.push(Nudge {
        path: format!("{mode}.{role}"),
        from: from.clone(),
        to: to.clone(),
        reason: format!(
            "reads {:.2} on {mode}.{}, needs {:?}",
            worst.0, worst.1, worst.2
        ),
    });
    colors.insert(role.to_string(), to);
}

/// True if any pair the UI draws fails in this mode's colors.
fn any_fail(c: &Colors) -> bool {
    pairs().into_iter().any(|(fg, bg, min)| {
        matches!((c.get(fg), c.get(bg)), (Some(f), Some(b)) if is_hex(f) && is_hex(b) && contrast(f, b) < min)
    })
}

/// Settles every text role. If some surface leaves no color that reads together with the
/// others (a mid-gray background with a light and a dark surface), that surface, and only a
/// surface, sunken or selection, moves toward the background until text can read. The
/// background itself never moves.
fn settle_all(mode: &str, mapped: &Colors) -> (Colors, Vec<Nudge>) {
    let run = |c: &mut Colors, n: &mut Vec<Nudge>| {
        for role in SETTLE {
            settle_role(mode, c, role, n);
        }
    };
    let mut c = mapped.clone();
    let mut n = Vec::new();
    run(&mut c, &mut n);
    if !any_fail(&c) {
        return (c, n);
    }
    let Some(bg) = mapped.get("background").cloned() else {
        return (c, n);
    };
    let bad: Vec<&str> = ["surface", "sunken", "selection"]
        .into_iter()
        .filter(|r| {
            pairs().into_iter().any(|(fg, b, min)| {
                b == *r
                    && matches!((c.get(fg), c.get(b)), (Some(f), Some(x)) if contrast(f, x) < min)
            })
        })
        .collect();
    // First only the surfaces that fail; then all three, since text that reads on a failing one
    // can still be unable to read on a surface that passes only because of that text.
    for set in [bad.clone(), vec!["surface", "sunken", "selection"]] {
        for step in 1..=20 {
            let t = f64::from(step) * 0.05;
            let mut c2 = mapped.clone();
            let mut n2 = Vec::new();
            for r in &set {
                if let Some(from) = mapped.get(*r) {
                    let to = mix(from, &bg, t);
                    if to != *from {
                        n2.push(Nudge {
                            path: format!("{mode}.{r}"),
                            from: from.clone(),
                            to: to.clone(),
                            reason: "leaves no text color that reads on it together with the other surfaces, so it moved toward the background".into(),
                        });
                        c2.insert((*r).to_string(), to);
                    }
                }
            }
            run(&mut c2, &mut n2);
            if !any_fail(&c2) {
                return (c2, n2);
            }
        }
    }
    (c, n)
}

/// Black or white for `on_accent` unless `first` reads on the accent.
fn on_accent_for(accent: &str, first: Option<&str>) -> String {
    first
        .into_iter()
        .chain(["#000000", "#ffffff"])
        .find(|c| contrast(c, accent) >= TEXT_MIN)
        .unwrap_or("#000000")
        .to_string()
}

/// The roles that are text or marks, in the order they are settled. Backgrounds are never moved.
const SETTLE: [&str; 7] = [
    "foreground",
    "strong",
    "muted",
    "urgent",
    "working",
    "done",
    "accent",
];

struct Mapped {
    mode: String,
    colors: Colors,
    fallbacks: Vec<String>,
}

fn map_colors(src: &Table, fallback_light: &Colors, fallback_dark: &Colors) -> Mapped {
    // The `mode` key, in any case. Without a usable one, the background decides.
    let named = src
        .get("mode")
        .and_then(Value::as_str)
        .map(|m| m.trim().to_lowercase());
    let mode = match named.as_deref() {
        Some("light") => "light",
        Some("dark") => "dark",
        _ => {
            let bg = ["background", "dark_background", "lighter_background"]
                .iter()
                .find_map(|k| src.get(*k).and_then(Value::as_str).and_then(norm_hex));
            match bg {
                Some(b) if contrast(&b, "#ffffff") < contrast(&b, "#000000") => "light",
                _ => "dark",
            }
        }
    };
    let fallback = if mode == "light" {
        fallback_light
    } else {
        fallback_dark
    };
    let mut colors = Colors::new();
    let mut fallbacks = Vec::new();
    for (role, keys) in MAP {
        let found = keys
            .iter()
            .find_map(|k| src.get(*k).and_then(Value::as_str).and_then(norm_hex));
        // A missing selection is the background pulled toward the text, never the base theme's
        // own, which may sit on the other side of the lightness range.
        let found = found.or_else(|| {
            let (bg, fg) = (colors.get("background")?, colors.get("foreground")?);
            (*role == "selection").then(|| mix(bg, fg, 0.15))
        });
        match found {
            Some(c) => {
                colors.insert((*role).to_string(), c);
            }
            None => {
                if let Some(own) = fallback.get(*role) {
                    fallbacks.push(format!(
                        "{mode}.{role}: this Omarchy theme has none of {}, so Polycarp's {own} is used",
                        keys.join(", ")
                    ));
                    colors.insert((*role).to_string(), own.clone());
                }
            }
        }
    }
    Mapped {
        mode: mode.to_string(),
        colors,
        fallbacks,
    }
}

