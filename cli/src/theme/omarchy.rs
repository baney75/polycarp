struct Built {
    text: String,
    mode: String,
    name: Option<String>,
    nudges: Vec<Nudge>,
    fallbacks: Vec<String>,
}

fn omarchy_theme_name(home: &Path) -> Option<String> {
    let raw = fs::read_to_string(state_dir(home).join("current/theme.name")).ok()?;
    let n = raw.trim();
    (!n.is_empty()
        && n.len() <= 64
        && n.chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, ' ' | '-' | '_' | '.')))
    .then(|| n.to_string())
}

fn build(cfg: &Cfg, home: &Path) -> Result<Built, ApiErr> {
    let path = colors_path(home);
    let meta = fs::metadata(&path).map_err(|e| {
        io_err(format!(
            "could not read Omarchy's colors at {}: {e}",
            path.display()
        ))
    })?;
    if !meta.is_file() || meta.len() > 256 * 1024 {
        return Err(io_err(format!(
            "{} is not a regular file of at most 256 KB",
            path.display()
        )));
    }
    let src = fs::read_to_string(&path)
        .map_err(|e| io_err(format!("could not read {}: {e}", path.display())))?;
    let table = parse_toml(&src)
        .map_err(|e| ApiErr::new("invalid_theme", format!("{}: {e}", path.display())))?;

    let base =
        resolve_name(cfg, BASE_THEME).map_err(|ps| bad_theme("the base theme is broken", &ps))?;
    let Mapped {
        mode,
        mut colors,
        fallbacks,
    } = map_colors(&table, &base.base.light, &base.base.dark);
    let other = if mode == "dark" { "light" } else { "dark" };

    let mut nudges = Vec::new();
    for role in SETTLE {
        settle_role(&mode, &mut colors, role, &mut nudges);
    }
    let bg = colors.get("background").cloned().unwrap_or_default();
    let accent = colors.get("accent").cloned().unwrap_or_default();
    colors.insert(
        "on_accent".into(),
        on_accent_for(&accent, Some(&bg).filter(|b| is_hex(b)).map(String::as_str)),
    );

    // The other mode keeps the base theme's colors, with Omarchy's accent moved only as far as it
    // needs to read on them.
    let mut rest = base.base.colors(other).clone();
    rest.insert("accent".into(), colors["accent"].clone());
    // The accent to start from is Omarchy's own, not the one already moved for this mode.
    let omarchy_accent = MAP
        .iter()
        .find(|(r, _)| *r == "accent")
        .and_then(|(_, keys)| {
            keys.iter()
                .find_map(|k| table.get(*k).and_then(Value::as_str).and_then(norm_hex))
        });
    if let Some(a) = omarchy_accent {
        rest.insert("accent".into(), a);
    }
    settle_role(other, &mut rest, "accent", &mut nudges);
    let other_accent = rest["accent"].clone();
    let other_on = on_accent_for(
        &other_accent,
        base.base.colors(other).get("on_accent").map(String::as_str),
    );

    let put = |c: &Colors, keys: &[&str]| {
        let mut t = Table::new();
        for k in keys {
            if let Some(v) = c.get(*k) {
                t.insert((*k).to_string(), Value::String(v.clone()));
            }
        }
        t
    };
    let roles: Vec<&str> = ROLES.to_vec();
    let mut doc = Table::new();
    doc.insert("name".into(), Value::String(THEME_NAME.into()));
    doc.insert("title".into(), Value::String("Omarchy".into()));
    doc.insert(
        "description".into(),
        Value::String(
            "The colors of the Omarchy system theme, on Omarchy's square, monospace look.".into(),
        ),
    );
    doc.insert("extends".into(), Value::String(BASE_THEME.into()));
    doc.insert(mode.clone(), Value::Table(put(&colors, &roles)));
    let mut other_colors = Colors::new();
    other_colors.insert("accent".into(), other_accent);
    other_colors.insert("on_accent".into(), other_on);
    doc.insert(
        other.to_string(),
        Value::Table(put(&other_colors, &["accent", "on_accent"])),
    );

    resolve_doc(cfg, doc.clone(), Some(THEME_NAME))
        .map_err(|ps| bad_theme("the Omarchy colors could not be made readable", &ps))?;

    let name = omarchy_theme_name(home);
    let body = toml::to_string(&doc).map_err(|e| io_err(e.to_string()))?;
    let text = format!(
        "{THEME_MARK}\n# Omarchy theme: {}. Do not edit: it is rewritten whenever Omarchy's theme changes.\n{body}",
        name.as_deref().unwrap_or("unknown")
    );
    Ok(Built {
        text,
        mode,
        name,
        nudges,
        fallbacks,
    })
}

/// Refuses to replace a user theme named `omarchy` that Polycarp did not write.
fn check_theme_file(cfg: &Cfg) -> Result<(), ApiErr> {
    let p = cfg.theme_path(THEME_NAME);
    match fs::read_to_string(&p) {
        Ok(t) if t.starts_with(THEME_MARK) => Ok(()),
        Ok(_) => Err(ApiErr::at(
            "exists",
            "name",
            format!(
                "{} already exists and was not written by `polycarp theme follow omarchy`, so it was not replaced",
                p.display()
            ),
        )
        .suggest("Rename or delete that theme, then run the command again.")),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(io_err(format!("could not read {}: {e}", p.display()))),
    }
}

