//! `polycarp theme follow omarchy`: match the Omarchy system theme, and follow it when it changes.
//!
//! The colors come from Omarchy's `colors.toml` through the same role mapping as
//! `spaces/scripts/gen-palettes.py`. Omarchy's colors are kept exactly wherever they already pass
//! the contrast rules; a role that fails is moved by the smallest lightness change that passes.

use super::*;

/// The second line of the hook script. A hook file without it is not ours and is never touched.
const HOOK_MARK: &str = "# polycarp-managed-hook";
/// The first line of the theme file we write. A user theme named `omarchy` without it is not ours.
const THEME_MARK: &str = "# Generated by `polycarp theme follow omarchy`.";
/// The generated colors. Rewritten on every Omarchy theme change.
pub(super) const THEME_NAME: &str = "omarchy";
/// The theme that is current while following: it extends `omarchy` and holds the person's changes,
/// so a sync never touches them.
pub(super) const TOP: &str = "omarchy-overrides";
const BASE_THEME: &str = "blocks";
const LOG_KEEP: usize = 50;
/// Lightness is searched in steps of this size (0.2 percentage points).
const STEP: f64 = 0.002;

/// Polycarp role -> Omarchy `colors.toml` keys, in order of preference. The first five lists are
/// `ROLES` in gen-palettes.py; the tails of `urgent`, `working`, `done` and `accent` are fallbacks
/// for older themes that lack the plain key.
const MAP: &[(&str, &[&str])] = &[
    ("background", &["background"]),
    ("surface", &["lighter_background", "background"]),
    ("sunken", &["dark_background", "background"]),
    ("foreground", &["foreground"]),
    (
        "strong",
        &["bright_foreground", "light_foreground", "foreground"],
    ),
    ("muted", &["dark_foreground", "muted"]),
    ("border", &["muted", "dark_foreground"]),
    ("accent", &["accent", "blue", "bright_blue"]),
    ("selection", &["selection", "lighter_background"]),
    ("urgent", &["red", "bright_red"]),
    ("working", &["yellow", "orange", "bright_yellow"]),
    ("done", &["green", "bright_green"]),
];

