fn home() -> Result<PathBuf, ApiErr> {
    match env::var_os("HOME")
        .filter(|h| !h.is_empty())
        .map(PathBuf::from)
    {
        Some(h) if h.is_absolute() => Ok(h),
        _ => Err(ApiErr::new(
            "config_error",
            "HOME is not set to an absolute path, so Omarchy's folders cannot be found",
        )),
    }
}

fn state_dir(home: &Path) -> PathBuf {
    home.join(".local/state/omarchy")
}

fn colors_path(home: &Path) -> PathBuf {
    state_dir(home).join("current/theme/colors.toml")
}

fn hook_path(home: &Path) -> PathBuf {
    home.join(".config/omarchy/hooks/theme-set.d/polycarp")
}

fn detected(home: &Path) -> bool {
    state_dir(home).is_dir()
}

fn no_omarchy(home: &Path) -> ApiErr {
    ApiErr::new(
        "no_omarchy",
        format!(
            "Omarchy was not found: {} does not exist. Nothing was changed",
            state_dir(home).display()
        ),
    )
    .suggest("This works only on a machine running Omarchy, for the person who uses it.")
}

