/// Following is on only while the settings hold the follow record and the theme is `omarchy`.
fn is_following(st: &State) -> bool {
    st.follow.is_some() && st.theme == THEME_NAME
}

fn nudge_notes(b: &Built) -> Vec<String> {
    b.fallbacks
        .iter()
        .cloned()
        .chain(b.nudges.iter().map(Nudge::note))
        .collect()
}

fn follow_data(b: &Built, hook: &Path) -> Json {
    json!({
        "following": true,
        "omarchy_theme": b.name,
        "omarchy_mode": b.mode,
        "nudges": b.nudges.iter().map(Nudge::json).collect::<Vec<_>>(),
        "hook": hook.display().to_string(),
    })
}

fn config_dir_for_hook(cfg: &Cfg) -> Option<PathBuf> {
    env::var_os("POLYCARP_CONFIG_DIR")
        .filter(|v| !v.is_empty())
        .map(|_| cfg.dir.clone())
}

/// Called by `set` and `apply` when another theme is chosen: forgets the follow record, and
/// returns a note and whether the hook should go.
pub(super) fn stop_for_switch(st: &mut State, chosen: &str, notes: &mut Vec<String>) -> bool {
    if st.follow.is_some() && chosen != THEME_NAME {
        st.follow = None;
        notes.push(
            "Polycarp was following Omarchy's theme; it no longer does, because you chose another theme"
                .into(),
        );
        return true;
    }
    false
}

/// Removes our hook after `stop_for_switch` said so, and says what happened.
pub(super) fn drop_hook(out: Out) -> Out {
    let Ok(h) = home() else { return out };
    match remove_hook(&hook_path(&h)) {
        Ok(msg) => {
            let mut out = out;
            out.notes.push(msg);
            out
        }
        Err(e) => out.caution(format!(
            "could not remove the Omarchy hook ({}); it does nothing while Polycarp is not following",
            e.message
        )),
    }
}

