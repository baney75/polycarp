pub(crate) fn op_follow(c: &Ctx, target: Option<&str>, sync: bool) -> Res {
    match (target, sync) {
        (Some(THEME_NAME), true) => op_sync(c),
        (_, true) => Err(ApiErr::usage("--sync goes with `omarchy`")),
        (Some(THEME_NAME), false) => follow_on(c),
        (Some("off"), false) => follow_off(c),
        (None | Some("status"), false) => status(c),
        (Some(_), false) => Err(ApiErr::usage(
            "expected `omarchy`, `off`, or nothing to see the state",
        )),
    }
}

fn status(c: &Ctx) -> Res {
    let home = home()?;
    let found = detected(&home);
    let (st, problems) = load_state(&c.cfg);
    let following = problems.is_empty() && is_following(&st);
    let hook = hook_path(&home);
    let hook_state = hook_state(&hook)?;
    let name = omarchy_theme_name(&home);
    let mut text = String::new();
    text.push_str(&format!(
        "omarchy: {}\n",
        if found { "found" } else { "not found" }
    ));
    text.push_str(&format!(
        "following: {}\n",
        if following { "yes" } else { "no" }
    ));
    if let (true, Some(f)) = (following, &st.follow) {
        text.push_str(&format!(
            "when you stop, the theme goes back to {} (mode {})\n",
            f.previous_theme, f.previous_mode
        ));
    }
    text.push_str(&format!(
        "hook: {} ({})\n",
        hook.display(),
        match hook_state {
            Hook::Absent => "not installed",
            Hook::Ours => "installed",
            Hook::Foreign => "someone else's file",
        }
    ));
    let data = json!({
        "omarchy_detected": found,
        "following": following,
        "omarchy_theme": name,
        "previous_theme": st.follow.as_ref().map(|f| f.previous_theme.clone()),
        "previous_mode": st.follow.as_ref().map(|f| f.previous_mode.clone()),
        "hook": hook.display().to_string(),
        "hook_installed": hook_state == Hook::Ours,
        "hook_foreign": hook_state == Hook::Foreign,
    });
    Ok(Out::new(data, text).warn(problems))
}

fn follow_on(c: &Ctx) -> Res {
    let home = home()?;
    if !detected(&home) {
        return Err(no_omarchy(&home));
    }
    let _lock = Lock::acquire(&c.cfg)?;
    let hook = hook_path(&home);
    let hook_before = hook_state(&hook)?;
    if hook_before == Hook::Foreign {
        return Err(refuse_foreign_hook(&hook));
    }
    check_theme_file(&c.cfg)?;
    let built = build(&c.cfg, &home)?;
    let exe = env::current_exe()
        .and_then(|p| p.canonicalize())
        .map_err(|e| io_err(format!("could not find this program's own path: {e}")))?;
    let script = hook_text(&exe, config_dir_for_hook(&c.cfg).as_deref())?;

    let (mut st, old_problems) = load_state(&c.cfg);
    let mut notes = Vec::new();
    if !old_problems.is_empty() {
        notes.push(format!(
            "the old settings were invalid and are replaced: {}",
            old_problems.join("; ")
        ));
    }
    let previous = match (&st.follow, st.theme == THEME_NAME) {
        (Some(f), _) => f.clone(),
        (None, true) => Follow {
            previous_theme: DEFAULT_THEME.into(),
            previous_mode: "auto".into(),
        },
        (None, false) => Follow {
            previous_theme: st.theme.clone(),
            previous_mode: st.mode.clone(),
        },
    };
    st.theme = THEME_NAME.into();
    st.mode = built.mode.clone();
    st.follow = Some(previous.clone());
    turn_on(&mut st, &mut notes);
    if st.accent_light.is_some() || st.accent_dark.is_some() {
        st.accent_light = None;
        st.accent_dark = None;
        notes.push("your accent override is cleared, so the accent is Omarchy's".into());
    }

    write_hook(&hook, &script)?;
    let mut out = match commit(
        c,
        Some(&st),
        "theme follow omarchy",
        Some((THEME_NAME, Some(&built.text))),
    ) {
        Ok(o) => o,
        Err(e) => {
            if hook_before == Hook::Absent {
                let _ = fs::remove_file(&hook);
            }
            return Err(e);
        }
    };
    notes.extend(nudge_notes(&built));
    notes.push(format!(
        "installed {}; Omarchy runs it after each theme change. `polycarp theme follow off` removes it",
        hook.display()
    ));
    out.notes.splice(0..0, notes);
    out.text = format!(
        "following Omarchy's theme{} ({} mode)\n{}",
        built
            .name
            .as_deref()
            .map(|n| format!(" {n:?}"))
            .unwrap_or_default(),
        built.mode,
        out.text
    );
    if !built.nudges.is_empty() {
        out.text.push_str(&format!(
            "{} color(s) were moved to read well; see notes\n",
            built.nudges.len()
        ));
    }
    Ok(out.with(follow_data(&built, &hook)))
}

fn follow_off(c: &Ctx) -> Res {
    let home = home()?;
    let hook = hook_path(&home);
    let _lock = Lock::acquire(&c.cfg)?;
    let (mut st, problems) = load_state(&c.cfg);
    let was = st.follow.clone();
    let mut out = match (&was, problems.is_empty()) {
        (Some(f), true) => {
            let mut notes = Vec::new();
            if st.theme == THEME_NAME {
                if resolve_name(&c.cfg, &f.previous_theme).is_ok() {
                    st.theme = f.previous_theme.clone();
                    st.mode = f.previous_mode.clone();
                } else {
                    st.theme = DEFAULT_THEME.into();
                    st.mode = "auto".into();
                    notes.push(format!(
                        "the theme you had before, {:?}, can no longer be used, so the default theme is back",
                        f.previous_theme
                    ));
                }
                if apply_accents(
                    &resolve_name(&c.cfg, &st.theme).map_err(|ps| bad_theme("theme", &ps))?,
                    st.accent_light.as_deref(),
                    st.accent_dark.as_deref(),
                )
                .is_err()
                {
                    st.accent_light = None;
                    st.accent_dark = None;
                }
            }
            st.follow = None;
            let mut o = commit(c, Some(&st), "theme follow off", None)?;
            o.notes.splice(0..0, notes);
            o.text = format!("stopped following Omarchy\n{}", o.text);
            o.with(json!({"following": false, "was_following": true}))
        }
        _ => {
            let mut o = Out::new(
                json!({"following": false, "was_following": false, "theme": st.theme, "mode": st.mode}),
                "Polycarp was not following Omarchy; no theme setting was changed\n",
            )
            .warn(problems);
            o.notes.push("no theme setting was changed".into());
            o
        }
    };
    match remove_hook(&hook) {
        Ok(msg) => out.notes.push(msg),
        Err(e) => out = out.caution(e.message),
    }
    out.data["hook"] = json!(hook.display().to_string());
    Ok(out)
}

fn op_sync(c: &Ctx) -> Res {
    let home = home()?;
    if !detected(&home) {
        return Err(no_omarchy(&home));
    }
    let _lock = Lock::acquire(&c.cfg)?;
    let (st, problems) = load_state(&c.cfg);
    if !problems.is_empty() || !is_following(&st) || !st.enabled {
        return Ok(Out::new(
            json!({"following": false, "changed": false}),
            "not following Omarchy, so nothing was done\n",
        ));
    }
    check_theme_file(&c.cfg)?;
    let built = build(&c.cfg, &home)?;
    let path = c.cfg.theme_path(THEME_NAME);
    let same_file = fs::read(&path).ok().as_deref() == Some(built.text.as_bytes());
    if same_file && st.mode == built.mode {
        return Ok(Out::new(
            json!({"following": true, "changed": false, "omarchy_theme": built.name}),
            "the Omarchy colors have not changed\n",
        ));
    }
    write_atomic(&path, built.text.as_bytes()).map_err(io_err)?;
    let mut st = st;
    st.mode = built.mode.clone();
    write_atomic(&c.cfg.file(), state_table(&c.cfg, &st).as_bytes()).map_err(io_err)?;
    let out = finish_with(&c.cfg, true)?;
    log_line(
        &c.cfg,
        &format!(
            "synced Omarchy theme {} ({}), {} color(s) moved",
            built.name.as_deref().unwrap_or("unknown"),
            built.mode,
            built.nudges.len()
        ),
    );
    let mut out = out.with(json!({
        "changed": true,
        "following": true,
        "omarchy_theme": built.name,
        "nudges": built.nudges.iter().map(Nudge::json).collect::<Vec<_>>(),
    }));
    out.notes.extend(nudge_notes(&built));
    Ok(out)
}

/// One line per sync in `follow.log`, newest last, the last 50 kept. A failure is ignored: the
/// log is a convenience and a hook must stay quiet.
fn log_line(cfg: &Cfg, line: &str) {
    let path = cfg.dir.join("follow.log");
    let (_, iso) = stamps();
    let old = fs::read_to_string(&path).unwrap_or_default();
    let mut lines: Vec<&str> = old.lines().collect();
    let new = format!("{iso} {line}");
    lines.push(&new);
    let keep = lines.len().saturating_sub(LOG_KEEP);
    let _ = write_atomic(&path, format!("{}\n", lines[keep..].join("\n")).as_bytes());
}

/// For `doctor`: a line when Omarchy is found, saying whether Polycarp follows it.
pub(crate) fn doctor_line() -> Option<String> {
    let home = home().ok()?;
    if !detected(&home) {
        return None;
    }
    let following = Cfg::from_env()
        .ok()
        .map(|cfg| load_state(&cfg))
        .is_some_and(|(st, p)| p.is_empty() && is_following(&st));
    let hook = hook_state(&hook_path(&home)).ok();
    Some(if following {
        if hook == Some(Hook::Ours) {
            "omarchy: found, and Polycarp is following its theme".to_string()
        } else {
            "omarchy: found, and Polycarp is following its theme, but the hook is missing, so it will not notice a switch. Run `polycarp theme follow omarchy` again".to_string()
        }
    } else {
        "omarchy: found; Polycarp is not following its theme. Run `polycarp theme follow omarchy` to match it".to_string()
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hsl_round_trips() {
        for c in [
            "#1a1b26", "#7aa2f7", "#ffffff", "#000000", "#808080", "#ff0000",
        ] {
            let (h, s, l) = to_hsl(c);
            assert_eq!(from_hsl(h, s, l), c);
        }
    }

    #[test]
    fn colors_are_normalized() {
        assert_eq!(norm_hex("#ABCDEF").as_deref(), Some("#abcdef"));
        assert_eq!(norm_hex("0xabcdef").as_deref(), Some("#abcdef"));
        assert_eq!(norm_hex("#abc").as_deref(), Some("#aabbcc"));
        assert_eq!(norm_hex("abcdef").as_deref(), Some("#abcdef"));
        assert_eq!(norm_hex("blue"), None);
        assert_eq!(norm_hex("#abcd"), None);
    }

    #[test]
    fn a_failing_color_moves_the_smallest_step() {
        let cons = vec![("background".to_string(), "#1a1b26".to_string(), 4.5)];
        let moved = nearest_passing("#414868", &cons, true).unwrap();
        assert!(contrast(&moved, "#1a1b26") >= 4.5);
        let (_, _, l0) = to_hsl("#414868");
        let (_, _, l1) = to_hsl(&moved);
        // One step less would not have passed.
        let (h, s, _) = to_hsl(&moved);
        assert!(!passes(&from_hsl(h, s, l1 - STEP), &cons));
        assert!(l1 > l0);
    }

    #[test]
    fn quoting_survives_a_quote() {
        assert_eq!(sh_quote("a'b"), "'a'\\''b'");
    }
}
